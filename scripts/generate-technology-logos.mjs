import { build } from 'esbuild';
import * as simple from 'simple-icons';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const dataset = JSON.parse(await readFile('node_modules/@iconify-json/logos/icons.json', 'utf8'));
const compiled = await build({
  entryPoints: ['packages/technology-detector/src/index.ts'],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
});
const { TECHNOLOGIES } = await import(
  'data:text/javascript;base64,' + Buffer.from(compiled.outputFiles[0].text).toString('base64')
);
const aliases = {
  'React Router':'react-router', 'Framer Motion':'framer', 'React Three Fiber':'react', 'React Three Drei':'threejs', 'Cloudflare Browser Insights':'cloudflare-icon',
  'Next.js': 'nextjs-icon',
  'Nuxt.js': 'nuxt-icon',
  'Vue.js': 'vue',
  jQuery: 'jquery',
  'Alpine.js': 'alpinejs-icon',
  HTMX: 'htmx',
  'D3.js': 'd3',
  'Chart.js': 'chartjs',
  'Three.js': 'threejs',
  'Google Analytics': 'google-analytics',
  'Google Tag Manager': 'google-tag-manager',
  'Microsoft Clarity': 'microsoft-icon',
  'Microsoft IIS': 'microsoft-icon',
  'ASP.NET': 'dotnet',
  'AWS CloudFront': 'aws-cloudfront',
  'Cloudflare Turnstile': 'cloudflare-icon',
  'Adobe Fonts': 'adobe-icon',
  'Google Fonts': 'google',
  'New Relic': 'new-relic',
  'Google reCAPTCHA': 'recaptcha',
  WooCommerce: 'woocommerce-icon',
  'Tailwind CSS': 'tailwindcss-icon',
  jsDelivr: 'jsdelivr',
  cdnjs: 'cloudflare-icon',
  UNPKG: 'unpkg',
  WordPress: 'wordpress-icon',
  Svelte: 'svelte-icon',
  React: 'react',
  Stripe: 'stripe',
  hCaptcha: 'hcaptcha-icon',
  PostHog: 'posthog-icon',
  Matomo: 'matomo-icon',
  Magento: 'magento',
  Plausible: 'plausibleanalytics',
};
const simpleAlias = {
  'Vue.js': 'vuedotjs',
  'Nuxt.js': 'nuxt',
  'Next.js': 'nextdotjs',
  'Alpine.js': 'alpinedotjs',
  'Chart.js': 'chartdotjs',
  'D3.js': 'd3dotjs',
  'Three.js': 'threedotjs',
  'ASP.NET': 'dotnet',
  'Google reCAPTCHA': 'googlerecaptcha',
  'Google Fonts': 'googlefonts',
  Plausible: 'plausibleanalytics',
  'Cloudflare Turnstile': 'cloudflare',
  'Adobe Fonts': 'adobefonts',
};
const icons = Object.values(simple).filter((v) => v && typeof v === 'object' && v.svg);
const vendorAssets = {
  Lenis:{file:'lenis.png',source:'https://lenis.darkroom.engineering/apple-touch-icon.png'},
  Crisp: { file: 'crisp.png', source: 'https://crisp.chat/favicons/favicon-128x128.png' },
  LiteSpeed: {
    file: 'litespeed.png',
    source: 'https://www.litespeedtech.com/images/logos/liteSpeed_logo_icon.png',
  },
  'Tawk.to': { file: 'tawkto.png', source: 'https://www.tawk.to/tawk-logo.png' },
};
const catalog = {},
  report = {},
  notices = [],
  missing = [];
await mkdir('assets/technologies', { recursive: true });
for (const name of [...new Set(TECHNOLOGIES.map((t) => t.name))].sort()) {
  const vendor = vendorAssets[name];
  if (vendor) {
    const bytes = await readFile('assets/technologies/' + vendor.file);
    if (bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a')
      throw new Error('Invalid vendor PNG');
    catalog[name] = { file: vendor.file };
    report[name] = 'data:image/png;base64,' + bytes.toString('base64');
    notices.push({
      technology: name,
      ...vendor,
      license: 'Vendor trademark asset; unmodified identifying logo',
    });
    continue;
  }
  const slug = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  const key = aliases[name] || name.toLowerCase().replace(/\./g, '').replace(/\s+/g, '-');
  const logo =
    name === 'Google Fonts' ? undefined : dataset.icons[key + '-icon'] || dataset.icons[key];
  let svg, source, license;
  if (logo) {
    svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${logo.width || dataset.width || 24} ${logo.height || dataset.height || 24}">${logo.body}</svg>`;
    source = `https://github.com/gilbarbara/logos (Iconify logos:${dataset.icons[key + '-icon'] ? key + '-icon' : key})`;
    license = 'CC0-1.0';
  } else {
    const icon = icons.find((i) => i.slug === (simpleAlias[name] || slug));
    if (icon) {
      svg = icon.svg.replace('<svg ', '<svg fill="#' + icon.hex + '" ');
      source = icon.source;
      license = icon.license?.type || 'CC0-1.0';
    }
  }
  if (!svg) {
    missing.push(name);
    continue;
  }
  if (/<script|<foreignObject|on\w+=|href="https?:/i.test(svg))
    throw new Error('Unexpected active SVG: ' + name);
  const file = slug + '.svg';
  await writeFile('assets/technologies/' + file, svg + '\n');
  catalog[name] = { file };
  report[name] = 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');
  notices.push({ technology: name, file, source, license });
}
await writeFile(
  'assets/technologies/catalog.ts',
  '// Generated by scripts/generate-technology-logos.mjs.\nexport const TECHNOLOGY_LOGOS: Record<string,{file:string}> = ' +
    JSON.stringify(catalog, null, 2) +
    ';\n'
);
await writeFile(
  'assets/technologies/report-logos.ts',
  '// Generated by scripts/generate-technology-logos.mjs.\nexport const TECHNOLOGY_REPORT_LOGOS: Record<string,string> = ' +
    JSON.stringify(report, null, 2) +
    ';\n'
);
await writeFile(
  'assets/technologies/SOURCES.json',
  JSON.stringify(
    {
      generatedAt: '2026-10-01',
      simpleIcons: JSON.parse(await readFile('node_modules/simple-icons/package.json')).version,
      iconifyLogos: dataset.lastModified,
      logos: notices,
      missing,
    },
    null,
    2
  ) + '\n'
);
console.log(
  `${notices.length} local technology logos generated. Missing: ${missing.join(', ') || 'none'}`
);
